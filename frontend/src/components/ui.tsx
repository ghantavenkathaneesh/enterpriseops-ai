import type { ReactNode } from 'react';
import type { Page } from '../types';

export function Loading() { return <div className="state" role="status">Loading…</div>; }
export function ErrorBox({ message, onRetry }: { message: string; onRetry?: () => void }) {
  return <div className="state error" role="alert">{message}{onRetry && <button className="btn small" onClick={onRetry}>Retry</button>}</div>;
}
export function Badge({ value }: { value: string }) { return <span className={`badge b-${value.toLowerCase()}`}>{value.replace('_', ' ')}</span>; }
export function StatCard({ label, value, hint }: { label: string; value: ReactNode; hint?: string }) {
  return <div className="card stat"><div className="stat-label">{label}</div><div className="stat-value">{value}</div>{hint && <div className="stat-hint">{hint}</div>}</div>;
}
export function SimulatedTag() { return <span className="badge b-simulated" title="Generated by the metric simulator, not real infrastructure">SIMULATED DATA</span>; }
export function PageHeader({ title, children }: { title: string; children?: ReactNode }) {
  return <div className="page-header"><h1>{title}</h1><div className="actions">{children}</div></div>;
}
export function Pager<T>({ page, onChange }: { page: Page<T>; onChange: (p: number) => void }) {
  if (page.totalPages <= 1) return null;
  return (
    <div className="pager">
      <button className="btn small" disabled={page.page === 0} onClick={() => onChange(page.page - 1)}>Previous</button>
      <span>Page {page.page + 1} of {page.totalPages} ({page.totalElements} items)</span>
      <button className="btn small" disabled={page.page + 1 >= page.totalPages} onClick={() => onChange(page.page + 1)}>Next</button>
    </div>
  );
}
export function Modal({ title, onClose, children }: { title: string; onClose: () => void; children: ReactNode }) {
  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal card" role="dialog" aria-label={title} onClick={(e) => e.stopPropagation()}>
        <div className="modal-head"><h2>{title}</h2><button className="btn small" onClick={onClose} aria-label="Close">✕</button></div>
        {children}
      </div>
    </div>
  );
}
export const fmt = (iso: string | null) => (iso ? new Date(iso).toLocaleString() : '—');
